INSERT INTO LANÇAMENTOS_FORMASDEPAGAMENTO
	([INCLUSAO] ,[EDICAO] ,[STATUS] ,[CONEXAOID] ,[LANCAMENTOID] ,[SP],[FORMADEPAGAMENTOID] ,[PARCELAS] ,[VALOR],
	[TEFID], [LANCAMENTODEVOLUCAO],[ORIGEMLANCAMENTOID],[PLANODEPAGAMENTOID] ,[TROCO],[DFEPAGAMENTOID])

SELECT
	[INCLUSAO],[EDICAO], @STATUS_PAR, [CONEXAOID], @LANCAMENTO_SEM_CONTA, [SP],@FORMA_PAGAMENTO_A_DEFINIR ,@PARCELAS,
	[VALOR], [TEFID], [LANCAMENTODEVOLUCAO],[ORIGEMLANCAMENTOID],[PLANODEPAGAMENTOID] ,[TROCO],[DFEPAGAMENTOID]

FROM LANÇAMENTOS_FORMASDEPAGAMENTO 
WHERE LANCAMENTOID = @LANCAMENTO_REFERENCIA



