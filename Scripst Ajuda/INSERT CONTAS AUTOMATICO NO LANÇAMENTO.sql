SELECT @LANCAMENTO_SEM_CONTA, [DATADAINCLUSÃO], [DATADEEDIÇÃO],[CONEXÃO], [NATUREZA], @STATUS_PAR, [DATADEVENCIMENTO],
	[DATADERECEBIMENTO], [CONEXÃODORECEBIMENTO], [DATADEPAGAMENTO], [CONEXÃODOPAGAMENTO], @VALOR_TOTAL_PRODUTOS_PP,
	@VALOR_TOTAL_PRODUTOS_PP, [CONTACORRENTE], [SP], @PARCELA, @PARCELAS, @FORMA_PAGAMENTO_A_DEFINIR

FROM CONTAS
WHERE LANÇAMENTO = @LANCAMENTO_REFERENCIA

